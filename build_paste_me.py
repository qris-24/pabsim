"""build_paste_me.py -- refresh the AUTO section of PASTE_ME.md at stage end.

Usage:  py -3.14 build_paste_me.py --stage CP<nn>

Writes only the text between <!-- AUTO:START --> and <!-- AUTO:END --> in
PASTE_ME.md. The MANUAL section and the markers themselves are never touched.
Exits non-zero, without writing, if a marker, VALIDATION_RESULTS.json or one of
the required CLAUDE.md sections is missing. Standard library only. LF endings.
Output is identical between runs except the build timestamp.
"""
import argparse
import datetime
import json
import os
import re
import subprocess
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.abspath(__file__))
PASTE_ME = os.path.join(ROOT, 'PASTE_ME.md')
RESULTS = os.path.join(ROOT, 'VALIDATION_RESULTS.json')
CLAUDE_MD = os.path.join(ROOT, 'CLAUDE.md')
AUTO_START = '<!-- AUTO:START -->'
AUTO_END = '<!-- AUTO:END -->'
CLAUDE_SECTIONS = ('## Open queue', '## Next stages', '## Commands')
CONTRACT_STATUSES = ('EXECUTED', 'EXECUTED_WITH_SUBSTITUTION',
                     'PARTIAL_EXECUTED', 'BLOCKED_UNSUPPORTED')
RESULT_KEYS = ('kernel_version', 'frozen_engines_modified',
               'full_card_behavior_verified', 'mass_replacement_sweep_allowed')


def fail(msg):
    sys.stderr.write('build_paste_me: %s\n' % msg)
    sys.exit(1)


def read(path):
    with open(path, 'r', encoding='utf-8', newline='') as fh:
        return fh.read()


def git(*args):
    try:
        out = subprocess.run(['git'] + list(args), cwd=ROOT, capture_output=True,
                             text=True, encoding='utf-8', errors='replace')
    except OSError:
        return None
    if out.returncode != 0:
        return None
    return out.stdout.rstrip('\n')


def claude_section(text, heading):
    """Return the section (heading line through the line before the next '## ')."""
    lines = text.split('\n')
    start = None
    for i, line in enumerate(lines):
        if line == heading or line.startswith(heading + ' ') or line.startswith(heading + ':'):
            start = i
            break
    if start is None:
        return None
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if lines[j].startswith('## '):
            end = j
            break
    body = lines[start:end]
    while body and body[-1].strip() == '':
        body.pop()
    return '\n'.join(body)


def latest_tag():
    out = git('tag', '-l', 'rp-CP*')
    if not out:
        return '(none)'
    tags = [t for t in out.split('\n') if re.fullmatch(r'rp-CP\d+[a-z]?', t)]

    def key(t):
        m = re.fullmatch(r'rp-CP(\d+)([a-z]?)', t)
        return (int(m.group(1)), m.group(2))
    return max(tags, key=key) if tags else '(none)'


def patch_notes():
    found = []
    for name in os.listdir(ROOT):
        m = re.fullmatch(r'CP(\d+)([a-z]?)_PATCH_NOTES\.md', name)
        if m:
            found.append(((int(m.group(1)), m.group(2)), name))
    found.sort(reverse=True)
    rows = []
    for _, name in found[:3]:
        heading = ''
        for line in read(os.path.join(ROOT, name)).split('\n'):
            if line.startswith('#'):
                heading = line.strip()
                break
        rows.append('- `%s`: %s' % (name, heading if heading else '(no heading)'))
    return rows


def build_auto(stage):
    if not os.path.isfile(RESULTS):
        fail('missing %s' % RESULTS)
    if not os.path.isfile(CLAUDE_MD):
        fail('missing %s' % CLAUDE_MD)
    with open(RESULTS, 'r', encoding='utf-8') as fh:
        res = json.load(fh)
    claude = read(CLAUDE_MD)
    sections = {}
    for heading in CLAUDE_SECTIONS:
        sec = claude_section(claude, heading)
        if sec is None:
            fail('CLAUDE.md section not found: %s' % heading)
        sections[heading] = sec

    head = git('log', '-1', '--format=%h %s') or '(git unavailable)'
    branch = git('rev-parse', '--abbrev-ref', 'HEAD') or '(git unavailable)'
    porcelain = git('status', '--porcelain')
    dirty = '(git unavailable)' if porcelain is None else str(
        len([l for l in porcelain.split('\n') if l.strip()]))

    contracts = res.get('contracts_executed') or {}
    counts = Counter()
    for v in contracts.values():
        counts[v.get('status') if isinstance(v, dict) else str(v)] += 1

    out = []
    out.append('## Stage state (auto-generated by build_paste_me.py; do not edit)')
    out.append('- Closing stage: %s' % stage)
    out.append('- Built: %s (local time)' % datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S'))
    out.append('- Branch: %s' % branch)
    out.append('- HEAD (parent of this stage\'s commit): %s' % head)
    out.append('- Latest rp-CP tag: %s' % latest_tag())
    out.append('- Uncommitted files (git status --porcelain): %s' % dirty)
    out.append('')
    out.append('## Gate (VALIDATION_RESULTS.json)')
    out.append('- tests_run / tests_passed: %s / %s'
               % (res.get('tests_run'), res.get('tests_passed')))
    out.append('- release gate passed / run: %s / %s'
               % (res.get('r02_release_gate_tests_passed'), res.get('r02_release_gate_tests_run')))
    for k in RESULT_KEYS:
        out.append('- %s: %s' % (k, json.dumps(res.get(k))))
    out.append('- contracts by status (%d total):' % len(contracts))
    for s in CONTRACT_STATUSES:
        out.append('  - %s: %d' % (s, counts.get(s, 0)))
    other = sorted(k for k in counts if k not in CONTRACT_STATUSES)
    for s in other:
        out.append('  - %s: %d' % (s, counts[s]))
    out.append('')
    for heading in CLAUDE_SECTIONS:
        out.append('<!-- CLAUDE.md %s (verbatim) -->' % heading)
        out.append(sections[heading])
        out.append('')
    out.append('## Latest patch notes')
    out.extend(patch_notes())
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--stage', required=True, help='closing stage, e.g. CP18')
    args = ap.parse_args()
    if not re.fullmatch(r'CP\d+[a-z]?', args.stage):
        fail('--stage must look like CP<nn>, got %r' % args.stage)
    if not os.path.isfile(PASTE_ME):
        fail('missing %s' % PASTE_ME)
    current = read(PASTE_ME)
    s = current.find(AUTO_START)
    e = current.find(AUTO_END)
    if s < 0 or e < 0 or e < s:
        fail('AUTO markers missing or out of order in PASTE_ME.md')
    auto = build_auto(args.stage)
    new = current[:s + len(AUTO_START)] + '\n' + auto + current[e:]
    new = new.replace('\r\n', '\n')
    with open(PASTE_ME, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(new)
    sys.stdout.write('%s %d bytes\n' % (PASTE_ME, os.path.getsize(PASTE_ME)))


if __name__ == '__main__':
    main()
